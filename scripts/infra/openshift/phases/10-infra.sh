#!/usr/bin/env bash
# Infra: Terraform creates the jump host, and the machine network it needs.
#
# Runs on: laptop (terraform apply, infra/terraform/environments/openshift).
#
# Why: installer-provisioned (IPI) OpenShift creates its own VMs, ports and
# security groups, but someone has to run it from inside the cloud, and with
# a bring-your-own network it also needs a subnet to land on. Terraform owns
# exactly that, so `openshift-install destroy` and `terraform destroy` never
# fight over the same resource.
#
# Creates (terraform.network.mode: create):
#   <cluster>-net / -subnet   machine network, DHCP pool excludes the VIPs
#   <cluster>-router          SNAT egress + floating IP path
#   <cluster>-jump            Ubuntu jump host on that subnet, with a FIP
#   2 more FIPs               API and ingress; the installer attaches them
#   ssh.pem                   one key: ubuntu@jump and core@<every node>
#
# Creates (terraform.network.mode: existing):
#   <cluster>-jump            Ubuntu jump host on the provider subnet named
#                             in the config, reached on its fixed IP
#   ssh.pem                   same key
# Nothing else: no network, subnet, router or floating IP, so a project with
# none of that quota can still build a cluster. The subnet's own gateway
# gives the nodes egress, and the VIPs are reached directly.
#
# Output: sensitive/openshift/<cluster>/cluster.env (IPs for later phases)
# Learn: terraform -chdir=infra/terraform/environments/openshift state list

"${REPO_ROOT}/scripts/lib/require-tools.sh" terraform
k8s_plat_require_os_credentials

ocp_step "terraform apply (${OCP_TF_DIR}, state ${OCP_TFSTATE})"
ocp_tf_vars
cd "${OCP_TF_DIR}"
k8s_plat_terraform_init "${OCP_TF_DIR}"
# shellcheck disable=SC2086
terraform apply -input=false ${OCP_AUTO_APPROVE} "${OCP_TF_VARS[@]}"

ocp_step "writing ${OCP_ENV_FILE}"
(
  umask 077
  cat >"${OCP_ENV_FILE}" <<EOF
# Generated by scripts/infra/openshift phase 10-infra — do not commit.
JUMP_SSH_IP=$(terraform output -raw jumphost_ssh_ip)
JUMP_FIP=$(terraform output -raw jumphost_floating_ip)
JUMP_FIXED_IP=$(terraform output -raw jumphost_fixed_ip)
API_FIP=$(terraform output -raw api_floating_ip)
INGRESS_FIP=$(terraform output -raw ingress_floating_ip)
MACHINE_CIDR=$(terraform output -raw machine_cidr)
NETWORK_NAME=$(terraform output -raw network_name)
SUBNET_NAME=$(terraform output -raw subnet_name)
SSH_PUBLIC_KEY=$(terraform output -raw ssh_public_key)
EOF
)
ocp_load_outputs

cat <<EOF

Jump host:   ssh -i ${OCP_SSH_KEY} ${OCP_JUMP}
Machine network: ${OCP_MACHINE_CIDR} (${OCP_NETWORK_NAME} / ${OCP_SUBNET_NAME})
VIPs (inside the subnet): API ${OCP_API_VIP}, ingress ${OCP_INGRESS_VIP}
EOF
if [[ "${OCP_NETWORK_MODE}" == "existing" ]]; then
  cat <<EOF
No floating IPs: the VIPs are reached directly, so ${OCP_API_HOST} and
*.${OCP_APPS_DOMAIN} point at the VIPs above from anywhere that routes to
${OCP_MACHINE_CIDR}.
EOF
else
  cat <<EOF
API FIP:     ${OCP_API_FIP}      -> ${OCP_API_HOST}
Ingress FIP: ${OCP_INGRESS_FIP}      -> *.${OCP_APPS_DOMAIN}
EOF
fi
